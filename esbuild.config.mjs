import esbuild from "esbuild";
import process from "process";

const production = process.argv[2] === "production";
const context = await esbuild.context({
  banner: {
    js: "/* Generated by esbuild from the TypeScript sources. */\n",
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "@codemirror/language",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  minify: production,
  sourcemap: production ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
});

if (production) {
  await context.rebuild();
  await context.dispose();
} else {
  await context.watch();
}
